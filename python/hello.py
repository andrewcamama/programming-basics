# Lines that start with # are comments. Python ignores them,
# they are notes for humans who read the code.

# input() shows a question and waits for the user to type an answer.
# The answer is saved in a variable called "name".
name = input("What's your name? ")

# print() shows text on the screen.
# The f before the quotes lets us put a variable inside { }.
print(f"Hello, {name}! Welcome to programming.")
