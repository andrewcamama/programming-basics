<?php
// Lines that start with // are comments. PHP ignores them.
// The <?php above tells the computer "PHP code starts here".

// In PHP, variables always start with a $ sign.
$name = "Andrew";

// echo shows text on the screen.
// Because we used double quotes, $name is replaced by its value.
// \n moves to a new line.
echo "Hello, $name! Welcome to programming.\n";
