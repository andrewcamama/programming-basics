// Lines that start with // are comments. Java ignores them.

// In Java, all code lives inside a class.
// The class name must match the file name (Hello.java).
public class Hello {

    // main is where the program starts running.
    public static void main(String[] args) {

        // "String" is the type for text. We save "Andrew" in the variable name.
        String name = "Andrew";

        // System.out.println() shows text on the screen.
        // The + sign joins pieces of text together.
        System.out.println("Hello, " + name + "! Welcome to programming.");
    }
}
